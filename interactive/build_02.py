PWD = "/home/alice/Movies"


def resolve(pwd, rel):
    """the parts of pwd + rel and, for each removed part, its pair number ('.' -> 0)"""
    base = [x for x in pwd.split("/") if x]
    toks = [[x, False, None] for x in base] + [[x, True, None] for x in rel.split("/") if x]
    kept, pair = list(range(len(base))), 0
    for i in range(len(base), len(toks)):
        n = toks[i][0]
        if n == "." or (n == ".." and not kept):
            toks[i][2] = 0
        elif n == "..":
            pair += 1
            toks[i][2] = pair
            toks[kept.pop()][2] = pair
        else:
            kept.append(i)
    return toks, "/" + "/".join(toks[i][0] for i in kept)


def calc(rel, absolute):
    toks, res = resolve(PWD, rel)
    assert res == absolute, (rel, res, absolute)
    join = "".join(f'<span class="{"r" if t[1] else "w"}">/{E(t[0])}</span>' for t in toks)
    red = ""
    for t in toks:
        seg = "/" + E(t[0])
        if t[2] is None:
            red += f'<span class="{"r" if t[1] else "w"}">{seg}</span>'
        elif t[2] == 0:
            red += f"<s>{seg}</s>"
        else:
            red += f'<s class="x{(t[2]-1)%3+1}">{seg}</s><sup class="x{(t[2]-1)%3+1}">{t[2]}</sup>'
    return (f'<div class="calcp"><div><div class="lb">🔗 <span class="w">pwd</span> + / + <span class="r">relative</span></div>{join}</div>'
            f'<div><div class="lb">✂️ drop every <code>.</code>, each <code>..</code> removes the directory before it</div>{red}</div>'
            f'<div><div class="lb">🌍 absolute path</div><b>{E(res)}</b></div></div>')


